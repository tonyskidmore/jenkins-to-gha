"""Markdown renderers for the harness sections of example READMEs and the migration report."""

from __future__ import annotations

import re
from typing import Any

from .convert.generator import AUTOMATION_WEIGHTS
from .docs import xref
from .ir import Pipeline, Stage

SEV_ICON = {"high": "🔴", "medium": "🟠", "low": "🟡", "info": "ℹ️"}
STATUS_ICON = {"mapped": "✅", "approximated": "🟡", "manual": "🔴", "dropped": "⚪", "info": "ℹ️"}
REVIEW_ORDER = ("manual", "approximated", "dropped", "mapped", "info")  # most work first; info is not scored
GROOVY_LOGIC = {"assign", "decl", "if", "for", "each", "while", "switch", "try", "return", "new"}
XREF_ALIASES = {"script": "scripted", "container": "podTemplate", "nested": "parallel", "failFast": "parallel"}


def stage_tree(ir: Pipeline | None) -> str:
    if ir is None:
        return "(no structure)"
    lines = []
    agent = ir.agent
    head = f"pipeline [{ir.dialect}]"
    if agent:
        head += f" agent: {agent.kind}" + (f" {agent.label or agent.image or ''}".rstrip() if (agent.label or agent.image) else "")
    lines.append(head)

    def steps_summary(st: Stage) -> str:
        names: dict[str, int] = {}

        def rec(steps):
            for s in steps:
                key = s.name if not s.receiver else f"{s.receiver.split('(')[0]}.{s.name}"
                names[key] = names.get(key, 0) + 1
                rec(s.body)
        rec(st.steps)
        return ", ".join(f"{k}×{v}" if v > 1 else k for k, v in list(names.items())[:8]) + (" …" if len(names) > 8 else "")

    def rec(stages: list[Stage], prefix: str):
        for i, st in enumerate(stages):
            last = i == len(stages) - 1
            branch = "└── " if last else "├── "
            tags = []
            if st.when:
                tags.append("when")
            if st.agent:
                tags.append(f"agent {st.agent.kind}")
            if st.input:
                tags.append("input")
            if st.parallel:
                tags.append("parallel")
            if st.matrix:
                tags.append("matrix " + " × ".join(f"{k}[{len(v)}]" for k, v in st.matrix.axes.items()))
            if st.post:
                tags.append("post: " + ",".join(st.post))
            lines.append(f"{prefix}{branch}{st.name or '(outside any stage)'}" + (f"  [{'; '.join(tags)}]" if tags else ""))
            child_prefix = prefix + ("    " if last else "│   ")
            if st.steps:
                lines.append(f"{child_prefix}· {steps_summary(st)}")
            rec(st.parallel, child_prefix)
            rec(st.stages, child_prefix)
            if st.matrix:
                rec(st.matrix.stages, child_prefix)
    rec(ir.stages, "")
    if ir.post:
        lines.append("post: " + ", ".join(ir.post))
    return "\n".join(lines)


def analysis_section(a: dict[str, Any], ir: Pipeline | None, env: dict[str, str]) -> str:
    m = a["metrics"]
    cx = a["complexity"]
    jm = a.get("jenkins_model")
    if jm is None:
        jv = "not checked (controller not running)"
    elif jm["result"] == "success":
        jv = "✅ valid Declarative (Jenkins `pipeline-model-converter/toJson`)"
    else:
        jv = "❌ " + "; ".join(e.split(" @ line")[0] for e in jm.get("errors", [])[:2])[:200]
        if a["dialect"] == "scripted":
            jv = "n/a (Scripted pipeline - Declarative model does not apply)"
    out = ["### Analysis (AST)\n",
           f"_Generated by `j2gha analyze` {env.get('date', '')}: Groovy AST from Jenkins-bundled Groovy "
           f"{env.get('groovy', '2.4')} (CONVERSION phase); Declarative model from Jenkins {env.get('jenkins', '?')}._\n",
           "| Property | Value |", "|---|---|",
           f"| Dialect | `{a['dialect']}` |",
           f"| Groovy parse | {'✅ ok' if a['parser']['ok'] else '❌ ' + str(a['parser']['errors'][:1])} |",
           f"| Jenkins validation | {jv} |",
           f"| Lines of code | {m.get('loc', 0)} |",
           f"| Stages | {m.get('stages', 0)} (max depth {m.get('max_stage_depth', 0)}), parallel branches "
           f"{m.get('parallel_branches', 0)}, matrix cells {m.get('matrix_cells', 0)} |",
           f"| Steps | {m.get('steps', 0)} ({m.get('distinct_steps', 0)} distinct, {m.get('shell_steps', 0)} shell, "
           f"{m.get('unknown_steps', 0)} unknown) |",
           f"| script{{}} blocks | {m.get('script_blocks', 0)} ({m.get('script_statements', 0)} Groovy statements) |",
           f"| Credentials referenced | {m.get('credentials', 0)} |",
           f"| Weighted mapping coverage | {a['coverage']['weighted_mapped_pct']}% |",
           f"| **Migration difficulty** | **{cx['score']}/100 - {cx['classification']}** |",
           f"| Convertibility | `{a['convertibility']}` |",
           ""]
    out += ["<details><summary>Difficulty dimensions</summary>\n", "| Dimension | Score | Max |", "|---|---:|---:|"]
    for k, v in cx["dimensions"].items():
        out.append(f"| {k.replace('_', ' ')} | {v} | {cx['weights'][k]} |")
    if cx["hard_gates"]:
        out.append(f"\nHard gates (force ≥ significant-redesign): {', '.join(cx['hard_gates'])}")
    out.append("\n</details>\n")
    out += ["**Stage graph** (j2gha IR)\n", "```text", stage_tree(ir), "```", ""]
    out += ["<details><summary>Step inventory</summary>\n", "| Step | Count | Category | GHA target | Lines |",
            "|---|---:|---|---|---|"]
    for name, e in list(a["steps"].items())[:40]:
        out.append(f"| `{name}` | {e['count']} | {e['category']} | {e.get('gha') or '-'} | "
                   f"{', '.join(str(x) for x in e['lines'][:6])} |")
    out.append("\n</details>\n")
    if a["findings"]:
        out += ["**Findings**\n", "| | Finding | Line | Evidence | Recommendation |", "|---|---|---:|---|---|"]
        for f in a["findings"][:20]:
            ev = str(f["evidence"]).replace("|", "\\|").replace("\n", " ")[:90]
            out.append(f"| {SEV_ICON[f['severity']]} | {f['id']}{' (gate)' if f.get('gate') else ''} | "
                       f"{f.get('line') or ''} | {ev} | {f['recommendation']} |")
        if len(a["findings"]) > 20:
            out.append(f"\n…and {len(a['findings']) - 20} more in `analysis/analysis.json`.")
    out.append("\nArtifacts: `analysis/analysis.json`, `analysis/ir.json`, `analysis/groovy-ast.json`, "
               "`analysis/jenkins-model.json`.")
    return "\n".join(out)


AUTOMATION_NOTE = ("Automation is an effort estimate: report items weighted by status ("
                   + ", ".join(f"{k} {w:g}" for k, w in AUTOMATION_WEIGHTS.items()) + "; info items are not scored), "
                   "not a measure of correctness.")


def conversion_section(report: dict[str, Any], workflow_path: str) -> str:
    c = report["counts"]
    out = ["### Conversion\n",
           f"Generated [`{workflow_path}`]({workflow_path}) and [`gha/migration-report.md`](gha/migration-report.md).\n",
           "| Mapped | Approximated | Manual | Dropped | Automation |", "|---:|---:|---:|---:|---:|",
           f"| {c.get('mapped', 0)} | {c.get('approximated', 0)} | {c.get('manual', 0)} | {c.get('dropped', 0)} | "
           f"{report['automation_pct']}% |", "",
           f"{AUTOMATION_NOTE}\n"]
    jobs = report["jobs"]
    out.append("Jobs: " + ", ".join(f"`{k}` ({v['runs-on']}{', matrix' if v['matrix'] else ''}, {v['steps']} steps)"
                                    for k, v in jobs.items()))
    if report["secrets"]:
        out.append("\nSecrets to create: " + ", ".join(f"`{k}`" for k in report["secrets"]))
    manual = [i for i in report["items"] if i["status"] == "manual"]
    if manual:
        out.append("\nManual items: " + "; ".join(f"{i['jenkins']}" + (f" (L{i['line']})" if i['line'] else "")
                                                for i in manual[:10]) + (" …" if len(manual) > 10 else ""))
    return "\n".join(out)


def xref_key(item: str) -> str | None:
    """Docs-crosswalk entry a migration-report item is about, or None.

    ``stage 'Build' when`` -> ``when``, ``options: timeout`` -> ``timeout`` (``options`` when the option has no
    entry), ``assign env.X = 1`` / ``helper() (local helper method)`` -> ``scripted``.
    """
    text = re.sub(r"^stage '.*?' ", "", item).replace("(no pipeline timeout)", "timeout")
    section = re.match(r"(options|triggers|parameters): *(\w+)", text)
    if section:
        return section[2] if xref.web_refs(section[2]) else section[1]
    if text.endswith("(local helper method)"):
        return "scripted"
    word = re.match(r"[A-Za-z_]\w*", text)
    if not word:
        return None
    term = "scripted" if word[0] in GROOVY_LOGIC else XREF_ALIASES.get(word[0], word[0])
    refs = xref.web_refs(term)
    return refs["key"] if refs else None


def references_section(items: list[dict[str, Any]]) -> list[str]:
    """Jenkins and GitHub Actions pages for each construct in ``items``, constructs needing the most work first.

    Always web links (see ``xref.web_refs``): the report is committed, so it must not depend on local bundles.
    """
    statuses: dict[str, list[str]] = {}
    for it in items:
        if key := xref_key(it["jenkins"]):
            statuses.setdefault(key, []).append(it["status"])
    if not statuses:
        return []
    first = {key: i for i, key in enumerate(statuses)}
    order = sorted(statuses, key=lambda k: (min(REVIEW_ORDER.index(s) for s in statuses[k]), first[k]))
    out = ["## Reference documentation\n",
           "Where to read about each construct above, most work first: jenkins.io and docs.github.com (GitHub.com) "
           "pages from the crosswalk in `j2gha/rules/docs-xref.yaml`. With the local docs bundles fetched, "
           "`uv run j2gha docs xref <construct>` resolves the same pages offline, or for another GitHub version.\n"]
    for key in order:
        refs = xref.web_refs(key)
        counts = ", ".join(f"{STATUS_ICON[s]} {statuses[key].count(s)} {s}" for s in REVIEW_ORDER if s in statuses[key])
        out.append(f"- **`{key}`** ({counts})" + (f": {refs['note']}" if refs["note"] else ""))
        for side, label in (("jenkins", "Jenkins"), ("gha", "GitHub Actions")):
            if refs[side]:
                out.append(f"  - {label}: " + " · ".join(f"[{text}]({url})" for text, url in refs[side]))
    out.append("")
    return out


def handoff_section(handoff: dict[str, Any] | None) -> list[str]:
    """What the workspace hand-off needs at run time and how far it reproduces Jenkins' one workspace."""
    if not handoff:
        return []
    def jobs(ids: list[str]) -> str:
        return ", ".join(f"`{j}`" for j in ids) or "none"
    return ["", "## Workspace hand-off\n",
            "Jenkins runs every stage without an agent of its own in one workspace; the converted jobs hand it on as "
            "`j2gha-ws-<job>` artifacts (an archive per job, kept one day) and restore it instead of checking out "
            "(`J2GHA_WORKSPACE_HANDOFF=0` converts without).\n",
            f"- **Handed on by:** {jobs(handoff['handed_on'])}. **Merged after running concurrently:** "
            f"{jobs(handoff['merged'])} (each later branch's own changes are replayed onto the first one's workspace).",
            "- **Runtime requirements:** bash, GNU tar, findutils, coreutils and sed on the runner and in job "
            "containers: GitHub's Linux runners and Debian/Ubuntu-based images. busybox/Alpine images fail at the "
            "hand-off steps.",
            "- **Same as Jenkins:** the files, directories, modes, symbolic and hard links every stage starts with, "
            "provided concurrent branches change different paths.",
            "- **Approximated:** concurrent branches do not see each other's files while they run; a path two of them "
            "change takes the later branch's version (in Jenkins: whichever wrote last); changes of timestamps alone "
            "and matrix cells' changes are not handed on.",
            "- **Fails instead:** an entry the job's user cannot read, a workspace that did not arrive from a job that "
            "ran - a nearest one or one the restore falls back on because a nearer job was skipped. Where that job's "
            "result is not visible to the restoring job (it is not one it needs directly), a missing workspace is taken "
            "as skipped, with a warning."]


def migration_report(meta: dict[str, Any], analysis: dict[str, Any], report: dict[str, Any], ir: Pipeline | None) -> str:
    repo = meta.get("repository", {})
    cx = analysis["complexity"]
    out = [f"# Migration report: {repo.get('full_name', '?')} `{meta.get('path', 'Jenkinsfile')}`\n",
           f"- **Classification:** {cx['classification']} (difficulty {cx['score']}/100)",
           f"- **Convertibility:** {analysis['convertibility']}",
           f"- **Automated mapping (effort estimate, not correctness):** {report['automation_pct']}% "
           f"({report['counts'].get('mapped', 0)} mapped, {report['counts'].get('approximated', 0)} approximated, "
           f"{report['counts'].get('manual', 0)} manual, {report['counts'].get('dropped', 0)} dropped)",
           f"- **Weighted step coverage (analysis):** {analysis['coverage']['weighted_mapped_pct']}%", ""]
    if report["secrets"]:
        out += ["## Secrets required\n", "| Secret | Purpose |", "|---|---|"]
        out += [f"| `{k}` | {v} |" for k, v in report["secrets"].items()]
        out.append("")
    gates = [f for f in analysis["findings"] if f.get("gate")]
    if gates:
        out += ["## Blocking items (hard gates)\n"]
        out += [f"- line {f.get('line') or '?'}: **{f['id']}** - {f['evidence']} → {f['recommendation']}" for f in gates]
        out.append("")
    out += ["## Mapping detail\n", "| | Jenkins | Line | Stage | GitHub Actions | Note |", "|---|---|---:|---|---|---|"]
    for it in report["items"]:
        out.append(f"| {STATUS_ICON.get(it['status'], '')} {it['status']} | `{it['jenkins']}` | {it['line'] or ''} | "
                   f"{it['stage'] or ''} | {it['gha']} | {it['note']} |")
    out += handoff_section(report.get("handoff"))
    if ir is not None and ir.notes:
        out += ["", "## Interpretation notes\n",
                "How the Jenkinsfile was read before conversion (scripted structure, approximations, statements the "
                "IR could not place):\n"]
        out += [f"- {n}" for n in ir.notes]
    out += ["", "## Stage graph\n", "```text", stage_tree(ir), "```", "",
            "## Assumptions\n",
            "- `when` conditions are evaluated once at stage entry (a step whose output the stage's steps test) against "
            "Jenkins-compatible env vars (`BRANCH_NAME`, `TAG_NAME`, `CHANGE_ID`...) defined at workflow level; hoist "
            "to job-level `if:` (github context) to save runner minutes.",
            "- An untranslatable condition becomes a repository variable `J2GHA_WHEN_L<line>` ('true'/'false'); while "
            "it is unset the stage runs only where it would run whatever that condition's value.",
            "- Stages sharing an agent run as steps of one job (shared workspace); parallel/matrix/agent/input stages "
            "become separate jobs. "
            + ("Jobs on the pipeline agent hand its workspace on (see *Workspace hand-off*); jobs with an agent of their "
               "own do not share it (use stash/unstash → artifacts)." if report.get("handoff") else
               "They do **not** share a workspace (use stash/unstash → artifacts)."),
            "- Actions are referenced by major version tag; pin to commit SHAs before production use (zizmor will flag this).",
            "- Shell steps run with `bash -e -o pipefail` (Jenkins `sh` uses `/bin/sh -xe`); a retried step runs each "
            "attempt as its own process with the same options.", ""]
    out += references_section(report["items"])
    return "\n".join(out)
