"""Example README rendering. Harness stages own marker-delimited sections so they can be re-run idempotently."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .config import WALKTHROUGH_MARKER

SECTIONS = ["header", "analysis", "conversion", "validation", "execution"]

PLACEHOLDER = {
    "analysis": "_Not analysed yet - run `uv run j2gha analyze {id}`._",
    "conversion": "_Not converted yet - run `uv run j2gha convert {id}`._",
    "validation": "_Not validated yet - run `uv run j2gha validate {id}`._",
    "execution": "_Not executed yet - run `uv run j2gha run {id} --tier jenkins,act`._",
}


def _marker(name: str, end: bool = False) -> str:
    return f"<!-- j2gha:{name}:{'end' if end else 'start'} -->"


def header_markdown(meta: dict[str, Any], titles: dict[str, str]) -> str:
    repo = meta["repository"]
    score = meta["score"]
    lines = []
    lic = repo.get("license") or "unknown"
    commit = meta.get("file_last_commit_sha")
    lines.append("## Source and citation\n")
    lines.append(f"- **Repository:** [{repo['full_name']}]({repo['html_url']})"
                 + (f" - {repo['description'].strip()}" if repo.get("description") else ""))
    lines.append(f"- **Original file:** [`{meta['path']}`]({meta['file_url']})")
    if commit:
        lines.append(f"- **File last changed:** {str(meta.get('file_last_commit_date', ''))[:10]} "
                     f"in commit [`{commit[:7]}`]({repo['html_url']}/commit/{commit})")
    lines.append(f"- **Repository last pushed:** {str(repo.get('pushed_at', ''))[:10]}"
                 + (" (archived)" if repo.get("archived") else ""))
    lines.append(f"- **Stars:** {repo.get('stargazers_count', 0):,} - **License:** {lic}"
                 + (f" ({repo['license_name']})" if repo.get("license_name") else ""))
    lines.append(f"- **Retrieved:** {meta['retrieved_at'][:10]} (blob `{meta['blob_sha'][:10]}`)")
    lines.append("")
    lines.append(f"> Citation: {repo['full_name'].split('/')[0]}, *{repo['full_name'].split('/')[1]}*, "
                 f"`{meta['path']}`, GitHub, {meta['file_url']} (accessed {meta['retrieved_at'][:10]}). "
                 f"The Jenkinsfile is copied verbatim for analysis and migration testing; all rights remain with "
                 f"the original authors under the repository's {lic} license.")
    lines.append("")
    lines.append("## Classification\n")
    lines.append(f"- **Primary style:** {titles.get(meta['primary_style'], meta['primary_style'])} (`{meta['primary_style']}`)")
    lines.append(f"- **Dialect:** `{meta['dialect']}`")
    lines.append("- **Styles detected:** " + ", ".join(f"`{s}`" for s in meta.get("styles", [])))
    crawl = meta.get("crawl_analysis", {})
    if crawl.get("complexity"):
        cx = crawl["complexity"]
        lines.append(f"- **Migration difficulty (crawl-time):** {cx['score']}/100 - {cx['classification']} "
                     f"(convertibility: {crawl.get('convertibility')})")
    lines.append("")
    lines.append(f"## Score: {score['total']} / 10\n")
    lines.append("| Criterion | Points | Max | Basis |")
    lines.append("|---|---:|---:|---|")
    names = {"repo_activity": "Repository activity", "file_freshness": "Jenkinsfile freshness",
             "complexity": "Complexity", "value": "Value / uniqueness", "popularity": "Popularity (stars)",
             "quality": "Quality"}
    for k, v in score["parts"].items():
        lines.append(f"| {names.get(k, k)} | {v['points']:.2f} | {v['max']} | {v['basis']} |")
    lines.append(f"| **Total** | **{score['total']}** | **10** | |")
    lines.append("")
    lines.append(f"**Why this score:** {score['summary']}")
    lines.append("")
    lines.append("_Scoring model: see [docs/scoring.md](../../docs/scoring.md)._")
    return "\n".join(lines)


def render_example_readme(meta: dict[str, Any], titles: dict[str, str]) -> str:
    repo = meta["repository"]
    parts = [f"# Example {meta['id']}: {repo['full_name']} - `{meta['path']}`", "",
             _marker("header"), header_markdown(meta, titles), _marker("header", True), "",
             "## Harness results", ""]
    for s in SECTIONS[1:]:
        parts += [_marker(s), PLACEHOLDER[s].format(id=meta["id"]), _marker(s, True), ""]
    return "\n".join(parts)


def section_file(readme: Path) -> Path:
    """Where stage sections go: the example README, or RESULTS.md beside a hand-written walkthrough README."""
    if readme.exists() and WALKTHROUGH_MARKER in readme.read_text():
        return readme.with_name("RESULTS.md")
    return readme


def update_section(readme: Path, section: str, markdown: str) -> None:
    target = section_file(readme)
    if target != readme and not target.exists():
        target.write_text(f"# Example {readme.parent.name}: harness results\n\n"
                          "_Generated by j2gha (not tracked in git); the walkthrough is [README.md](README.md)._\n")
    readme = target
    text = readme.read_text() if readme.exists() else ""
    start, end = _marker(section), _marker(section, True)
    block = f"{start}\n{markdown.strip()}\n{end}"
    if start in text and end in text:
        text = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    readme.write_text(text)


def update_header(readme: Path, meta: dict[str, Any], titles: dict[str, str]) -> None:
    update_section(readme, "header", header_markdown(meta, titles))
